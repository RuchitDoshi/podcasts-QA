"""
Generates reference ("ground truth") answers for eval/queries.yaml's scored
queries -- needed for RAGAS-style answer_correctness, which requires
comparing the system's answer against a known-correct reference, something
this project didn't have until now (the existing query set only has
expected_episode_id, not a written correct answer).

Uses a strong model via LiteLLM (default: Claude Sonnet) run through the
SAME real agent (agent/orchestrator.py's run_agent) used everywhere else in
this project -- not a separate, ad hoc retrieval pipeline. This keeps
references grounded in the actual corpus (retrieved and cited via the real
tool-calling loop, same citation verification applied) rather than the
strong model's free-form background knowledge, which would defeat the
purpose of a RAG-specific ground truth: a reference answer should reflect
what's actually IN this corpus, not what a frontier model happens to know
about the topic in general.

References are cached to a file and NOT regenerated on every eval run --
generating them costs real money (frontier-model pricing) and a ground
truth should be a stable target to measure against, not something that
silently drifts between runs just because the eval script was re-run.
Use --force to regenerate everything, or --query to regenerate one.

A reference generated this way is a "silver" reference, not a gold one --
it's a strong model's best answer given the real retrieved content, spot-
checked by a human is still worthwhile before fully trusting it, since
answer_correctness scores are only as good as what they're compared against.

Usage:
    python eval/generate_references.py
    python eval/generate_references.py --force
    python eval/generate_references.py --query "What does Kaldellis say about Justinian's legal reforms?"
"""

import argparse
import logging
import sys
import time
from datetime import UTC, datetime
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from agent.orchestrator import AgentContext, get_client_for_provider, run_agent  # noqa: E402

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
log = logging.getLogger("generate_references")

# A frontier-tier model, confirmed present in this project's LiteLLM catalog
# -- used specifically for reference-answer QUALITY, not as the system under
# test. Deliberately a stronger/different model than whatever eval_answers.py
# is evaluating, so references aren't circularly generated by the same
# model being judged.
DEFAULT_REFERENCE_MODEL = "us.anthropic.claude-sonnet-4-5-20250929-v1:0"


def load_queries(path: Path) -> list[dict]:
    with open(path) as f:
        return yaml.safe_load(f).get("queries", [])


def load_existing_references(path: Path) -> dict:
    if not path.exists():
        return {}
    with open(path) as f:
        data = yaml.safe_load(f) or {}
    return data.get("references", {})


def generate_reference(query: str, ctx: AgentContext, client, model: str) -> dict | None:
    """Runs the real agent with a strong model to produce a grounded
    reference answer. Returns None (not cached) if the result was an
    infra failure or a genuine decline -- a reference answer needs to
    actually BE an answer to be useful as a correctness target."""
    result = run_agent(query, ctx, client, model)

    if result.get("infra_failure"):
        log.warning("Infra failure generating reference for %r -- skipping, not caching", query)
        return None

    if not result["has_answer"]:
        log.warning(
            "Reference model declined to answer %r (has_answer=False) -- skipping. "
            "If this is unexpected, check whether the corpus genuinely lacks this content.",
            query,
        )
        return None

    if not result["all_citations_verified"]:
        log.warning(
            "Reference model's citations for %r didn't fully verify -- skipping rather than "
            "caching a reference that isn't fully grounded",
            query,
        )
        return None

    return {
        "reference_answer": result["answer"],
        "citations": [
            {"chunk_id": c["chunk_id"], "episode_id": c["episode_id"]} for c in result["citations"]
        ],
        "model": model,
        "generated_at": datetime.now(UTC).isoformat(),
    }


def main():
    parser = argparse.ArgumentParser(
        description="Generate reference answers for answer_correctness"
    )
    parser.add_argument("--queries", type=Path, default=Path("eval/queries.yaml"))
    parser.add_argument(
        "--chunks",
        type=Path,
        default=Path("/home/ruchit/ruchit-personal/datasets/podcast-audio-chunks"),
    )
    parser.add_argument("--config", type=Path, default=Path("config/settings.yaml"))
    parser.add_argument("--episodes-config", type=Path, default=Path("config/episodes.yaml"))
    parser.add_argument("--output", type=Path, default=Path("eval/reference_answers.yaml"))
    parser.add_argument("--provider", type=str, choices=["groq", "litellm"], default="litellm")
    parser.add_argument("--model", type=str, default=DEFAULT_REFERENCE_MODEL)
    parser.add_argument(
        "--force", action="store_true", help="Regenerate every reference, even cached ones"
    )
    parser.add_argument(
        "--query", type=str, default=None, help="Regenerate just one query, by exact text"
    )
    parser.add_argument("--sleep-between-queries", type=float, default=4.0)
    args = parser.parse_args()

    with open(args.config) as f:
        settings = yaml.safe_load(f)

    all_queries = load_queries(args.queries)
    scored_queries = [q for q in all_queries if q.get("expected_episode_id")]
    if args.query:
        scored_queries = [q for q in scored_queries if q["query"] == args.query]
        if not scored_queries:
            log.error("No scored query found matching %r", args.query)
            sys.exit(1)

    existing = {} if args.force else load_existing_references(args.output)

    ctx = AgentContext(settings, args.chunks, args.episodes_config)
    client = get_client_for_provider(args.provider)

    references = dict(existing)
    for i, spec in enumerate(scored_queries):
        query = spec["query"]
        if query in existing and not args.force and not args.query:
            log.info("[%d/%d] Skipping (already cached): %s", i + 1, len(scored_queries), query)
            continue

        log.info("[%d/%d] Generating reference for: %s", i + 1, len(scored_queries), query)
        ref = generate_reference(query, ctx, client, args.model)
        if ref:
            references[query] = ref

        if i < len(scored_queries) - 1:
            time.sleep(args.sleep_between_queries)

    args.output.parent.mkdir(parents=True, exist_ok=True)
    with open(args.output, "w") as f:
        yaml.safe_dump(
            {"references": references}, f, sort_keys=False, allow_unicode=True, width=100
        )

    log.info("Saved %d reference answers to %s", len(references), args.output)


if __name__ == "__main__":
    main()
